  pw.Widget _healthSummaryBlock(HealthSnapshot snapshot) {
    final items = <String, String?>{
      'Sleep vs baseline': snapshot.sleepVsBaselineSummary,
      'Steps vs baseline': snapshot.stepsVsBaselineSummary,
      'Heart rate vs baseline': snapshot.hrVsBaselineSummary,
    };

    return pw.Container(
      padding: const pw.EdgeInsets.all(10),
      decoration: pw.BoxDecoration(
        color: _kGrey100,
        borderRadius: const pw.BorderRadius.all(pw.Radius.circular(6)),
        border: pw.Border.all(color: _kGrey300, width: 0.5),
      ),
      child: pw.Column(
