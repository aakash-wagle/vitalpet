/// Generates the doctor handoff PDF and shares it via the native share sheet.
/// Pure Dart — no native bridge required.
/// Writes [AuditEvent.handoffExport] before sharing.
class HandoffGenerator {
  const HandoffGenerator();

  /// Full pipeline:
  /// 1. Load check-ins from DB for the last [dayCount] days
  /// 2. Build de-identified [NarrativeContext]
  /// 3. Generate clinical narrative (rule-based or SLM)
  /// 4. Build pw.Document with up to 3 pages
  /// 5. Write HANDOFF_EXPORT audit entry
  /// 6. Share via native share sheet — VitalPet never observes the destination
  Future<void> generateAndShare({
    required int dayCount,
    required WidgetRef ref,
  }) async {
    final now = DateTime.now().toUtc();
    final endDay = DateTime(now.year, now.month, now.day);
    final startDay = endDay.subtract(Duration(days: dayCount - 1));
    final startStr = _fmt(startDay);
    final endStr = _fmt(endDay);

    // 1. Load check-ins
    final checkIns = await ref
        .read(checkInDaoProvider)
        .findByDateRange(startStr, endStr);

    // 2. Optional health data
    final healthAdapter = const HealthAdapter();
    final healthSnapshot = await healthAdapter.fetchSummary(
      start: startDay,
      end: endDay,
    );

    // 3. Build chart data
    final trendPoints =
        ChartDataBuilder.buildTrendChart(checkIns, startDay, endDay);
    final heatmap = ChartDataBuilder.buildHeatmap(checkIns);
    final symptomFreq = ChartDataBuilder.buildSymptomFrequency(checkIns);
    final notableEvents = ChartDataBuilder.buildNotableEvents(trendPoints);

    // 4. Aggregate stats (de-identified)
    final completed = checkIns.where((c) => !c.isPartial).length;
    final avgWellness = checkIns.isEmpty
        ? 0.0
        : checkIns
                .map((c) => c.overallStatus == 'great' ? 8.0 : 3.0)
                .reduce((a, b) => a + b) /
            checkIns.length;
    final trend = _computeTrend(trendPoints);
    final sortedDomains = (symptomFreq.entries.toList()
          ..sort((a, b) => b.value.compareTo(a.value)))
        .map((e) => e.key)
        .toList();

    final narrativeCtx = NarrativeContext(
      dayCount: dayCount,
      averageWellnessScore: avgWellness,
      dominantSymptomDomains: sortedDomains.take(3).toList(),
      deviationAlertSummaries: notableEvents
          .take(5)
          .map((e) =>
              '${DateFormat('MMM d').format(e.date)}: ${e.reason}')
          .toList(),
      trendDirection: trend,
      symptomFrequency: symptomFreq,
      mostFrequentPainRegions: _extractPainRegions(checkIns),
      fatigueBlockedDailyCount: _countFatigueBlocked(checkIns),
      totalCheckins: dayCount,
      completedCheckins: completed,
      healthCorrelationSummary: healthSnapshot != null
          ? [
              healthSnapshot.sleepVsBaselineSummary,
              healthSnapshot.stepsVsBaselineSummary,
            ].whereType<String>().join('; ')
          : null,
    );

    // 5. Generate narrative
    final narrative =
        await ref.read(narrativeGeneratorProvider).generate(narrativeCtx);

    // 6. Build PDF
    final pdf = pw.Document(
      title: 'VitalPet Health Summary',
      author: 'VitalPet',
      subject: 'Wellness Report',
    );

    pdf.addPage(_buildPage1(
      ctx: narrativeCtx,
      narrative: narrative,
      trendPoints: trendPoints,
      sortedDomains: sortedDomains,
      symptomFreq: symptomFreq,
      completed: completed,
      avgWellness: avgWellness,
      startStr: startStr,
      endStr: endStr,
    ));

    pdf.addPage(_buildPage2(
      heatmap: heatmap,
      notableEvents: notableEvents,
      startDay: startDay,
      trendPoints: trendPoints,
    ));

    if (healthSnapshot != null) {
      pdf.addPage(_buildPage3(
        healthSnapshot: healthSnapshot,
        trendPoints: trendPoints,
      ));
    }

    // 7. Write audit entry BEFORE sharing (never log the destination)
    final dateRangeStr = '$startStr/$endStr';
    final payloadHash =
        sha256.convert(utf8.encode(dateRangeStr)).toString();
    await ref
        .read(auditLogDaoProvider)
        .append(AuditEvent.handoffExport(payloadHash: payloadHash));

    // 8. Share via native share sheet (printing package — pure Dart)
    final bytes = Uint8List.fromList(await pdf.save());
    await Printing.sharePdf(
      bytes: bytes,
      filename:
          'vitalpet_summary_${DateFormat('yyyyMMdd').format(DateTime.now())}.pdf',
    );
  }

