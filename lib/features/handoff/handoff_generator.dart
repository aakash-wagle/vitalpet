  static String _fmt(DateTime d) =>
      '${d.year.toString().padLeft(4, '0')}-'
      '${d.month.toString().padLeft(2, '0')}-'
      '${d.day.toString().padLeft(2, '0')}';

  /// Computes trend direction from the first and last halves of trend scores.
  static String _computeTrend(List<TrendPoint> points) {
    final scored = points.where((p) => p.score != null).toList();
    if (scored.length < 4) return 'stable';

    final half = scored.length ~/ 2;
    final firstHalfAvg =
        scored.take(half).map((p) => p.score!).reduce((a, b) => a + b) / half;
    final secondHalfAvg = scored
            .skip(half)
            .map((p) => p.score!)
            .reduce((a, b) => a + b) /
        (scored.length - half);

    final delta = secondHalfAvg - firstHalfAvg;
    if (delta > 0.75) return 'improving';
    if (delta < -0.75) return 'declining';
    return 'stable';
  }

  static List<String> _extractPainRegions(List<CheckIn> checkIns) {
    final regionCount = <String, int>{};
    for (final ci in checkIns) {
      final answers = _parseAnswers(ci.answersJson);
      final symptoms = (answers['symptoms'] as List<dynamic>?) ?? [];
      for (final s in symptoms) {
        final sMap = s as Map<String, dynamic>;
        if (sMap['category'] != 'pain') continue;
        final regions = (sMap['regions'] as List<dynamic>?) ?? [];
        for (final r in regions) {
          final region = r as String?;
          if (region != null) {
            regionCount[region] = (regionCount[region] ?? 0) + 1;
          }
        }
      }
    }
    return (regionCount.entries.toList()
          ..sort((a, b) => b.value.compareTo(a.value)))
        .map((e) => e.key)
        .take(5)
        .toList();
  }

  static int _countFatigueBlocked(List<CheckIn> checkIns) {
    var count = 0;
    for (final ci in checkIns) {
      final answers = _parseAnswers(ci.answersJson);
      final symptoms = (answers['symptoms'] as List<dynamic>?) ?? [];
      for (final s in symptoms) {
        final sMap = s as Map<String, dynamic>;
        if (sMap['category'] == 'fatigue' && sMap['blocks_daily'] == true) {
          count++;
          break; // count once per session
        }
      }
    }
    return count;
  }

  static Map<String, dynamic> _parseAnswers(String json) {
    try {
      return jsonDecode(json) as Map<String, dynamic>;
    } catch (_) {
      return {};
    }
  }

  static List<TrendPoint> _samplePoints(
    List<TrendPoint> points, {
    required int maxCount,
  }) {
    if (points.length <= maxCount) return points;
    final step = points.length / maxCount;
    return [
      for (var i = 0; i < maxCount; i++) points[(i * step).round().clamp(0, points.length - 1)],
    ];
  }

  static PdfColor _scoreToHeatColor(int? score) {
    if (score == null) return _kGrey300;
    if (score <= 2) return _kDanger;
    if (score <= 4) return PdfColor.fromInt(0xFFFF7043);
    if (score <= 6) return _kWarning;
    if (score <= 8) return _kPrimaryLight;
    return _kSuccess;
  }

  static String _formatCategory(String cat) {
    return switch (cat) {
      'fever' => 'Fever',
      'pain' => 'Pain',
      'fatigue' => 'Fatigue',
      'nausea' => 'Nausea',
      'other' => 'Other',
      _ => _capitalize(cat),
    };
  }

  static String _capitalize(String s) =>
      s.isEmpty ? s : '${s[0].toUpperCase()}${s.substring(1)}';
