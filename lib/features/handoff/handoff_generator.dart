  pw.Widget _symptomFreqBar(
    List<String> sortedDomains,
    Map<String, int> symptomFreq,
  ) {
    if (sortedDomains.isEmpty) {
      return pw.Text(
        'No symptoms recorded in this period.',
        style: pw.TextStyle(fontSize: 9, color: _kGrey600),
      );
    }
    final maxCount = symptomFreq.values.reduce((a, b) => a > b ? a : b);
    final top = sortedDomains.take(5).toList();

    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: top.map((domain) {
        final count = symptomFreq[domain] ?? 0;
        final fraction = maxCount > 0 ? count / maxCount : 0.0;
        return pw.Padding(
          padding: const pw.EdgeInsets.only(bottom: 4),
          child: pw.Row(
            children: [
              pw.SizedBox(
                width: 60,
                child: pw.Text(
                  _formatCategory(domain),
                  style: pw.TextStyle(fontSize: 8.5, color: _kTextPrimary),
                ),
              ),
              pw.SizedBox(
                width: 200,
                child: pw.Row(
                  children: [
                    pw.Container(
                      width: 200 * fraction,
                      height: 10,
                      decoration: const pw.BoxDecoration(
                        color: _kPrimary,
                        borderRadius:
                            pw.BorderRadius.all(pw.Radius.circular(3)),
                      ),
                    ),
                    pw.Container(
                      width: 200 * (1 - fraction),
                      height: 10,
                      decoration: const pw.BoxDecoration(
                        color: _kGrey300,
                        borderRadius:
                            pw.BorderRadius.all(pw.Radius.circular(3)),
                      ),
                    ),
                  ],
                ),
              ),
              pw.SizedBox(width: 6),
              pw.Text(
                '$count sessions',
                style: pw.TextStyle(fontSize: 8, color: _kGrey600),
              ),
            ],
          ),
        );
      }).toList(),
    );
  }

  pw.Widget _trendChart(List<TrendPoint> points) {
    // Sample to at most 30 points for clarity on the chart
    final sampledPoints = _samplePoints(points, maxCount: 30);
    final hasData = sampledPoints.any((p) => p.score != null);

    if (!hasData) {
      return pw.Container(
        height: 80,
        alignment: pw.Alignment.center,
        child: pw.Text(
          'No wellness data in this period.',
          style: pw.TextStyle(fontSize: 9, color: _kGrey600),
        ),
      );
    }

    final indexedPoints = sampledPoints.asMap().entries.toList();
    final chartData = indexedPoints
        .where((e) => e.value.score != null)
        .map((e) => pw.PointChartValue(
              e.key.toDouble(),
              e.value.score!.toDouble(),
            ))
        .toList();

    return pw.SizedBox(
      height: 100,
      child: pw.Chart(
        grid: pw.CartesianGrid(
          xAxis: pw.FixedAxis<int>(
            List<int>.generate(sampledPoints.length, (i) => i),
            divisions: false,
            color: _kGrey300,
          ),
          yAxis: pw.FixedAxis<int>(
            const [0, 2, 4, 6, 8, 10],
            format: (v) => '$v',
            divisions: true,
            divisionsColor: _kGrey300,
          ),
        ),
        datasets: [
          pw.LineDataSet(
            legend: 'Wellness (1–10)',
            drawSurface: true,
            isCurved: true,
            color: _kPrimary,
            data: chartData,
          ),
        ],
      ),
    );
  }

  pw.Widget _calendarHeatmap(Map<String, int?> heatmap) {
    final now = DateTime.now();
    // Build 42 cells: 6 weeks × 7 days, oldest→newest left-to-right, top→bottom
    final cells = <MapEntry<DateTime, int?>>[];
    for (var i = 41; i >= 0; i--) {
      final date = DateTime(now.year, now.month, now.day)
          .subtract(Duration(days: i));
      final key = _fmt(date);
      cells.add(MapEntry(date, heatmap[key]));
    }

    final dayLabels = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];

    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        // Day-of-week header
        pw.Row(
          children: dayLabels
              .map((d) => pw.Expanded(
                    child: pw.Text(
                      d,
                      style: pw.TextStyle(fontSize: 6.5, color: _kGrey600),
                      textAlign: pw.TextAlign.center,
                    ),
                  ))
              .toList(),
        ),
        pw.SizedBox(height: 3),
        // 6 weeks of cells
        for (var week = 0; week < 6; week++)
          pw.Padding(
            padding: const pw.EdgeInsets.only(bottom: 2),
            child: pw.Row(
              children: [
                for (var day = 0; day < 7; day++)
                  pw.Expanded(
                    child: pw.Container(
                      height: 14,
                      margin: const pw.EdgeInsets.symmetric(horizontal: 1),
                      decoration: pw.BoxDecoration(
                        color: _scoreToHeatColor(
                            cells[week * 7 + day].value),
                        borderRadius:
                            const pw.BorderRadius.all(pw.Radius.circular(2)),
                      ),
                    ),
                  ),
              ],
            ),
          ),
      ],
    );
  }

