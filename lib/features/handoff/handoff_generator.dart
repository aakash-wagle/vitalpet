  pw.Widget _summaryStatsRow({
    required int completed,
    required int dayCount,
    required double avgWellness,
    required String trend,
  }) {
    final completionPct = dayCount > 0 ? ((completed / dayCount) * 100).round() : 0;
    return pw.Row(
      children: [
        _statBox('Check-ins', '$completed/$dayCount\n($completionPct%)'),
        pw.SizedBox(width: 8),
        _statBox('Avg Wellness', '${avgWellness.toStringAsFixed(1)}/10'),
        pw.SizedBox(width: 8),
        _statBox(
          'Trend',
          _capitalize(trend),
          boxColor: trend == 'improving'
              ? _kSuccess
              : trend == 'declining'
                  ? _kDanger
                  : _kWarning,
        ),
      ],
    );
  }

